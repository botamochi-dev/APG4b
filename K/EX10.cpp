#include <bits/stdc++.h>
using namespace std;

int main() {
  int A, B;
  cin >> A >> B;

  // ここにプログラムを追記
  cout << "A:" ;
  int i = 0;
  while (A > i) {
      cout << "]";
      i++;
  }
  cout << endl;

  cout << "B:" ;
  i = 0;
  while (B > i) {
      cout << "]";
      i++;
  }
  cout << endl;
}
